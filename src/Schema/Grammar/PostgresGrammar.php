<?php declare(strict_types=1);

namespace Rajtik\Migrations\Schema\Grammar;

use Rajtik\Migrations\Schema\ColumnDefinition;
use Rajtik\Migrations\Schema\ColumnType;


final class PostgresGrammar extends Grammar
{
	public function wrap(string $identifier): string
	{
		return '"' . str_replace('"', '""', $identifier) . '"';
	}


	public function supportsTransactionalDdl(): bool
	{
		return true;
	}


	public function compileDropAllTables(array $tables): array
	{
		return $tables === []
			? []
			: ['drop table ' . implode(', ', array_map($this->wrap(...), $tables)) . ' cascade'];
	}


	protected function type(ColumnDefinition $column): string
	{
		return match ($column->type) {
			ColumnType::Id => 'bigint generated by default as identity primary key',
			ColumnType::Integer => 'integer',
			ColumnType::BigInteger, ColumnType::ForeignId => 'bigint',
			ColumnType::String => 'varchar(' . $column->length . ')',
			ColumnType::Text => 'text',
			ColumnType::Boolean => 'boolean',
			ColumnType::Timestamp => 'timestamp(0) without time zone',
		};
	}


	protected function value(string|int|float|bool|null $value): string
	{
		return is_bool($value) ? ($value ? 'true' : 'false') : parent::value($value);
	}


	protected function compileDropIndex(string $table, string $name): string
	{
		return 'drop index ' . $this->wrap($name);
	}


	protected function compileDropForeign(string $table, string $name): string
	{
		return 'alter table ' . $this->wrap($table) . ' drop constraint ' . $this->wrap($name);
	}
}
